public class Smallmaths {
public static double multiplication (double first, double second) {
  double  multiply = first * second ;
    
return multiply; 
    }
public static double Substraction (double first, double second) {
        double substract;
  if (first < second){
  substract = second - first ;
  }
  else {
  substract = first - second;
  }

    
return (substract); 
    }
public static double Addition (double first, double second) {
   double add = first + second ;
    
return add; 
    }
public static double Division (double first, double second) {
   double divide = first / second ;
    
return divide; 
    }
    
}
